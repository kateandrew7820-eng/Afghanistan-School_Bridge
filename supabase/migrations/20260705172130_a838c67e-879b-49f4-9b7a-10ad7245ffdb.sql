
-- ============================================================
-- 1) Broaden write policies on provinces / districts / schools
--    Existing "Admins can manage ..." already uses is_admin() which
--    covers both 'admin' and 'ministry_admin'. Nothing to change there.
--    Add explicit ministry_admin catch-all for schools INSERT/UPDATE/DELETE
--    (schools currently has principal/admin scoped policies only).
-- ============================================================

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='schools' AND policyname='Ministry admins can manage all schools') THEN
    CREATE POLICY "Ministry admins can manage all schools"
      ON public.schools FOR ALL TO authenticated
      USING (public.is_admin())
      WITH CHECK (public.is_admin());
  END IF;
END $$;

-- Ensure GRANTs are in place
GRANT SELECT, INSERT, UPDATE, DELETE ON public.provinces TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.districts TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.schools TO authenticated;
GRANT ALL ON public.provinces TO service_role;
GRANT ALL ON public.districts TO service_role;
GRANT ALL ON public.schools TO service_role;

