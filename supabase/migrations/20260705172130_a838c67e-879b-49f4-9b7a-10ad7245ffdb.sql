-- Ensure uniqueness constraint exists
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'districts_province_name_unique'
  ) THEN
    ALTER TABLE public.districts
      ADD CONSTRAINT districts_province_name_unique UNIQUE (province_id, name);
  END IF;
END $$;

